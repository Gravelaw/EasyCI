"""Render administrator-reviewed Jenkins UI pipeline scripts from project contracts."""
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('ci', ROOT / 'scripts/ci.py')
ci = importlib.util.module_from_spec(spec); spec.loader.exec_module(ci)


def render(project):
    p = ci.config(project)
    windows = p['platform'] == 'windows-wsl'
    runner = 'bat' if windows else 'sh'
    python = 'python' if windows else 'python3'
    tools = 'C:/JenkinsLocal/tools' if windows else '/opt/local-ci'
    snapshots = 'C:/JenkinsLocal/snapshots/juliaflow' if windows else '/snapshots'
    releases = 'C:/JenkinsLocal/releases/juliaflow' if windows else '/home/jenkins/releases'
    v = lambda name: f'%{name}%' if windows else f'${name}'
    invocation = f'{python} "{v("CI_TOOLS")}/scripts/ci.py"'
    common = f'--project {project} --work "{v("CI_WORK")}"'
    prepare = f'{invocation} prepare {common} --snapshots "{v("CI_SNAPSHOTS")}" --snapshot-id "{v("SNAPSHOT_ID")}" --metadata-sha256 "{v("METADATA_SHA256")}"'
    execute = f'{invocation} run {common}'
    promote = f'{invocation} promote {common} --releases "{v("CI_RELEASES")}" --reviewed-result-sha256 "{v("REVIEWED_RESULT_SHA256")}"'
    prefix = '@echo off\n' if windows else 'set -eu\n'
    return f"""// Generated by scripts/render-pipelines.py; review before administrator installs in UI.
// Trusted snapshot ingestion only. No SCM local-checkout override or automatic trigger.
properties([
  disableConcurrentBuilds(),
  buildDiscarder(logRotator(numToKeepStr: '20', daysToKeepStr: '30', artifactNumToKeepStr: '10')),
  parameters([
    string(name: 'SNAPSHOT_ID', defaultValue: '', description: 'Approved immutable snapshot ID'),
    string(name: 'METADATA_SHA256', defaultValue: '', description: 'SHA-256 of reviewed snapshot.json')
  ])
])
if (!(params.SNAPSHOT_ID ==~ /[a-z][a-z0-9-]{{0,79}}/) ||
    !(params.METADATA_SHA256 ==~ /[0-9a-f]{{64}}/)) {{
  error('Reviewed snapshot identifier and metadata checksum required')
}}
timeout(time: {p['timeoutMinutes'] + 25}, unit: 'MINUTES') {{
  lock(resource: '{p['heavyLock']}') {{
    node('{p['agentLabel']}') {{
      withEnv([
        'CI_TOOLS={tools}', 'CI_SNAPSHOTS={snapshots}', 'CI_RELEASES={releases}',
        "CI_WORK=${{env.WORKSPACE}}/runs/${{env.BUILD_NUMBER}}",
        "SNAPSHOT_ID=${{params.SNAPSHOT_ID}}", "METADATA_SHA256=${{params.METADATA_SHA256}}"
      ]) {{
        try {{
          stage('Prepare reviewed commit') {{
            {runner} '''{prefix}{prepare}'''
          }}
          stage('Build and validate once') {{
            timeout(time: {p['timeoutMinutes']}, unit: 'MINUTES') {{
              {runner} '''{prefix}{execute}'''
            }}
          }}
          def reviewedHash = readFile("runs/${{env.BUILD_NUMBER}}/result.sha256").trim()
          if (!(reviewedHash ==~ /[0-9a-f]{{64}}/)) {{ error('Invalid result checksum') }}
          archiveArtifacts(artifacts: "runs/${{env.BUILD_NUMBER}}/result*", fingerprint: true)
          stage('Review exact tested artifact') {{
            echo readFile("runs/${{env.BUILD_NUMBER}}/result.json")
            def approval
            timeout(time: 20, unit: 'MINUTES') {{
              approval = input(message: "Approve local promotion of result SHA-256 ${{reviewedHash}}?",
                ok: 'Promote locally', submitter: '{p['reviewer']}', submitterParameter: 'REVIEWER',
                parameters: [booleanParam(name: 'APPROVE', defaultValue: false,
                  description: 'I reviewed candidate, artifact checksum, phases and cleanup evidence')])
            }}
            if (approval['APPROVE'] != true || approval['REVIEWER'] != '{p['reviewer']}') {{
              error('Explicit approved reviewer required')
            }}
            withEnv(["CI_REVIEWER=${{approval['REVIEWER']}}", "REVIEWED_RESULT_SHA256=${{reviewedHash}}"]) {{
              stage('Promote same bytes') {{
                {runner} '''{prefix}{promote}'''
              }}
            }}
          }}
        }} finally {{
          // Preserve failed/interrupted evidence; no broad deleteDir/prune.
          archiveArtifacts(artifacts: "runs/${{env.BUILD_NUMBER}}/*.json,runs/${{env.BUILD_NUMBER}}/*.sha256",
            allowEmptyArchive: true, fingerprint: true)
          echo 'Run workspace retained for ownership-checked operator cleanup. Follow docs/operations.md.'
        }}
      }}
    }}
  }}
}}
"""


if __name__ == '__main__':
    for project in ('demo', 'juliaflow'):
        (ROOT / 'pipelines' / f'{project}.Jenkinsfile').write_text(render(project), encoding='utf-8', newline='\n')
    print('Rendered two reviewed pipeline templates')
